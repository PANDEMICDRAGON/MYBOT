import math
import time
import logging
from typing import Dict, Any, List

logging.basicConfig(level=logging.INFO, format='%(asctime)s - %(levelname)s - %(message)s')
logger = logging.getLogger("RollerMillQuadratureInspector")

class RollerMillQuadratureInspector:
    """
    Measures and correlates harmonic amplitude phase quadrature resolver signals
    for roller mill spindles to prevent torque ripple anomalies.
    """
    def __init__(self, mill_id: str, base_frequency_hz: float = 50.0):
        self.mill_id = mill_id
        self.base_frequency_hz = base_frequency_hz
        self.telemetry_history: List[Dict[str, float]] = []

    def sample_resolver(self, raw_sin: float, raw_cos: float, timestamp: float) -> Dict[str, float]:
        """
        Computes instantaneous phase angle, quadrature error, and estimated torque ripple.
        """
        angle_rad = math.atan2(raw_sin, raw_cos)
        amplitude = math.sqrt(raw_sin**2 + raw_cos**2)
        quadrature_error = abs(raw_sin) - abs(raw_cos)
        estimated_torque_ripple = amplitude * math.sin(2.0 * angle_rad)

        metrics = {
            "timestamp": timestamp,
            "angle_rad": angle_rad,
            "amplitude": amplitude,
            "quadrature_error": quadrature_error,
            "estimated_torque_ripple": estimated_torque_ripple
        }
        self.telemetry_history.append(metrics)
        if len(self.telemetry_history) > 1000:
            self.telemetry_history.pop(0)
        return metrics

    def inspect_synchronization(self) -> Dict[str, Any]:
        """
        Evaluates stability across recent telemetry readings.
        """
        if not self.telemetry_history:
            return {"status": "INSUFFICIENT_DATA", "health_score": 1.0}

        recent = self.telemetry_history[-50:]
        avg_amplitude = sum(m["amplitude"] for m in recent) / len(recent)
        max_ripple = max(abs(m["estimated_torque_ripple"]) for m in recent)
        
        health_score = max(0.0, 1.0 - (max_ripple / (avg_amplitude + 1e-6)))
        status = "OPTIMAL" if health_score > 0.85 else "ATTENTION_REQUIRED"

        return {
            "mill_id": self.mill_id,
            "status": status,
            "health_score": health_score,
            "average_amplitude": avg_amplitude,
            "peak_torque_ripple": max_ripple
        }

