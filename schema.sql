-- Supabase Database Schema for 24/7 Web Collector Bot
-- Run this script in your Supabase SQL Editor (https://supabase.com/dashboard/project/_/sql)

-- 1. Table to store URLs and CSS selectors to monitor
CREATE TABLE IF NOT EXISTS bot_targets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    url TEXT NOT NULL,
    selector TEXT NOT NULL DEFAULT 'title',
    active BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. Table to store deduplicated scraped outputs
CREATE TABLE IF NOT EXISTS bot_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    target_id BIGINT REFERENCES bot_targets(id) ON DELETE CASCADE,
    source_url TEXT NOT NULL,
    content_hash TEXT UNIQUE NOT NULL,
    extracted_data TEXT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Indexes for performance and quick hash lookup
CREATE INDEX IF NOT EXISTS idx_bot_records_hash ON bot_records(content_hash);
CREATE INDEX IF NOT EXISTS idx_bot_targets_active ON bot_targets(active);
