-- 6. AI Tactical Briefings (Defensive Protocols & Asymmetric Upside Analysis)
CREATE TABLE IF NOT EXISTS tactical_briefings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    threat_level TEXT NOT NULL, -- 'NOMINAL', 'ELEVATED', 'CRITICAL'
    sitrep TEXT NOT NULL,
    conflict_summary TEXT,
    future_risk_forecast TEXT,
    defensive_protocol TEXT,
    asymmetric_upside TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

