-- =====================================================================
CREATE INDEX IF NOT EXISTS idx_weather_scope ON weather_reports(scope);
CREATE INDEX IF NOT EXISTS idx_news_scope_created ON news_articles(scope, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_cyber_created ON cyber_alerts(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_conflict_created ON conflict_and_macro_intel(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_conflict_domain ON conflict_and_macro_intel(domain);
CREATE INDEX IF NOT EXISTS idx_conflict_theater ON conflict_and_macro_intel(theater);
CREATE INDEX IF NOT EXISTS idx_briefings_created ON tactical_briefings(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_tasks_due ON personal_tasks(completed, notified, due_at);
CREATE INDEX IF NOT EXISTS idx_ledger_created ON personal_ledger(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_vault_created ON idea_vault(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_osint_created ON osint_dossiers(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_osint_type ON osint_dossiers(entity_type);

