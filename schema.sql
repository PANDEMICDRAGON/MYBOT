-- =====================================================================
-- Supabase Database Schema for 24/7 Web Collector, Weather, News & Cyber Bot
-- Execute in Supabase SQL Editor (https://supabase.com/dashboard/project/_/sql)
-- =====================================================================

-- 1. Weather Reports Table (Upserted per city to prevent unbounded storage bloat)
CREATE TABLE IF NOT EXISTS weather_reports (
    city TEXT PRIMARY KEY,
    scope TEXT NOT NULL, -- 'LOCAL' or 'GLOBAL'
    temp_c NUMERIC(4,1) NOT NULL,
    humidity INT NOT NULL,
    wind_kmh NUMERIC(5,1) NOT NULL,
    condition TEXT NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. News Articles Table (Deduplicated via SHA-256 Title+Link hash)
CREATE TABLE IF NOT EXISTS news_articles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scope TEXT NOT NULL, -- 'LOCAL' or 'GLOBAL'
    source TEXT NOT NULL,
    title TEXT NOT NULL,
    link TEXT NOT NULL,
    content_hash TEXT UNIQUE NOT NULL,
    published_at TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. Cybersecurity Alerts & Active CVEs (CISA KEV + Threat Intel + Local Cyber)
CREATE TABLE IF NOT EXISTS cyber_alerts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category TEXT NOT NULL, -- 'CVE-KEV', 'THREAT-INTEL', or 'LOCAL-CYBER'
    source TEXT NOT NULL,
    cve_id TEXT,            -- Populated for CISA Known Exploited Vulnerabilities
    severity TEXT NOT NULL, -- 'CRITICAL', 'HIGH', or 'ADVISORY'
    title TEXT NOT NULL,
    summary TEXT,
    link TEXT NOT NULL,
    content_hash TEXT UNIQUE NOT NULL,
    published_at TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. Dynamic Custom Target & Record Tables (For custom web scraping)
CREATE TABLE IF NOT EXISTS bot_targets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    url TEXT NOT NULL,
    selector TEXT NOT NULL DEFAULT 'title',
    active BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS bot_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    target_id BIGINT REFERENCES bot_targets(id) ON DELETE CASCADE,
    source_url TEXT NOT NULL,
    content_hash TEXT UNIQUE NOT NULL,
    extracted_data TEXT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- =====================================================================
-- Indexes for High Performance & Query Optimization
-- =====================================================================
CREATE INDEX IF NOT EXISTS idx_weather_scope ON weather_reports(scope);
CREATE INDEX IF NOT EXISTS idx_news_scope_created ON news_articles(scope, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_news_content_hash ON news_articles(content_hash);
CREATE INDEX IF NOT EXISTS idx_cyber_created ON cyber_alerts(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_cyber_category ON cyber_alerts(category);
CREATE INDEX IF NOT EXISTS idx_cyber_content_hash ON cyber_alerts(content_hash);
CREATE INDEX IF NOT EXISTS idx_bot_records_hash ON bot_records(content_hash);
CREATE INDEX IF NOT EXISTS idx_bot_targets_active ON bot_targets(active);

-- =====================================================================
-- Row Level Security (RLS) - Read-only for Website Public anon Key
-- =====================================================================
ALTER TABLE weather_reports ENABLE ROW LEVEL SECURITY;
ALTER TABLE news_articles ENABLE ROW LEVEL SECURITY;
ALTER TABLE cyber_alerts ENABLE ROW LEVEL SECURITY;
ALTER TABLE bot_targets ENABLE ROW LEVEL SECURITY;
ALTER TABLE bot_records ENABLE ROW LEVEL SECURITY;

-- Allow public anonymous reads for the Vercel web dashboard
DROP POLICY IF EXISTS "Allow public read on weather" ON weather_reports;
CREATE POLICY "Allow public read on weather"
ON weather_reports FOR SELECT TO anon USING (true);

DROP POLICY IF EXISTS "Allow public read on news" ON news_articles;
CREATE POLICY "Allow public read on news"
ON news_articles FOR SELECT TO anon USING (true);

DROP POLICY IF EXISTS "Allow public read on cyber_alerts" ON cyber_alerts;
CREATE POLICY "Allow public read on cyber_alerts"
ON cyber_alerts FOR SELECT TO anon USING (true);

-- Allow authenticated/service_role full access for Python bot backend writes
DROP POLICY IF EXISTS "Allow service full access on weather" ON weather_reports;
CREATE POLICY "Allow service full access on weather"
ON weather_reports FOR ALL TO service_role USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Allow service full access on news" ON news_articles;
CREATE POLICY "Allow service full access on news"
ON news_articles FOR ALL TO service_role USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Allow service full access on cyber_alerts" ON cyber_alerts;
CREATE POLICY "Allow service full access on cyber_alerts"
ON cyber_alerts FOR ALL TO service_role USING (true) WITH CHECK (true);
