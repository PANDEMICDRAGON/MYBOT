-- 5. AI Tactical Briefings (Stores synthesized Cortana/JARVIS SitReps for the Web HUD)
CREATE TABLE IF NOT EXISTS tactical_briefings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    threat_level TEXT NOT NULL, -- 'NOMINAL', 'ELEVATED', 'CRITICAL'
    sitrep TEXT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 6. Contextual Calendar & Task Assistant Table
CREATE TABLE IF NOT EXISTS personal_tasks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    priority TEXT NOT NULL DEFAULT 'NORMAL', -- 'CRITICAL', 'HIGH', 'NORMAL'
    due_at TIMESTAMPTZ,
    notified BOOLEAN DEFAULT FALSE,
    completed BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 7. Information & Receipt Organizer (M-Pesa, Bank SMS, Invoices, Tickets)
CREATE TABLE IF NOT EXISTS personal_ledger (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ref_code TEXT,                           -- Transaction ID / Confirmation Code
    amount NUMERIC(12,2) NOT NULL DEFAULT 0,
    currency TEXT NOT NULL DEFAULT 'KES',
    counterparty TEXT NOT NULL,              -- Merchant, Sender, or Recipient
    category TEXT NOT NULL,                  -- 'EXPENSE', 'INCOME', 'RECEIPT', 'TICKET'
    raw_summary TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 8. Quick Voice-to-Action Logger (Project Ideas, Lyrics, Code Architectures)
CREATE TABLE IF NOT EXISTS idea_vault (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tag TEXT NOT NULL,                       -- 'PROJECT', 'CODE', 'MUSIC', 'GENERAL'
    content TEXT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 9. Dynamic Custom Target & Record Tables (For custom web scraping)
CREATE TABLE IF NOT EXISTS bot_targets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    url TEXT NOT NULL,
    selector TEXT NOT NULL DEFAULT 'title',
    active BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS bot_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    target_id BIGINT REFERENCES bot_targets(id) ON DELETE CASCADE,
    source_url TEXT NOT NULL,
    content_hash TEXT UNIQUE NOT NULL,
    extracted_data TEXT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- =====================================================================
-- Indexes for High Performance & Query Optimization
-- =====================================================================
CREATE INDEX IF NOT EXISTS idx_weather_scope ON weather_reports(scope);
CREATE INDEX IF NOT EXISTS idx_news_scope_created ON news_articles(scope, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_cyber_created ON cyber_alerts(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_cyber_category ON cyber_alerts(category);
CREATE INDEX IF NOT EXISTS idx_briefings_created ON tactical_briefings(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_tasks_due ON personal_tasks(completed, notified, due_at);
CREATE INDEX IF NOT EXISTS idx_ledger_created ON personal_ledger(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_vault_created ON idea_vault(created_at DESC);

