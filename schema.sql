-- 1. Weather Reports Table (Upserted per city to prevent unbounded storage bloat)
CREATE TABLE IF NOT EXISTS weather_reports (
    city TEXT PRIMARY KEY,
    scope TEXT NOT NULL, -- 'LOCAL' or 'GLOBAL'
    temp_c NUMERIC(4,1) NOT NULL,
    humidity INT NOT NULL,
    wind_kmh NUMERIC(5,1) NOT NULL,
    condition TEXT NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. News Articles Table (Deduplicated via SHA-256 Title+Link hash)
CREATE TABLE IF NOT EXISTS news_articles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scope TEXT NOT NULL, -- 'LOCAL' or 'GLOBAL'
    source TEXT NOT NULL,
    title TEXT NOT NULL,
    link TEXT NOT NULL,
    content_hash TEXT UNIQUE NOT NULL,
    published_at TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. Cybersecurity Alerts & Active CVEs (CISA KEV + Threat Intel + Local Cyber)
CREATE TABLE IF NOT EXISTS cyber_alerts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category TEXT NOT NULL, -- 'CVE-KEV', 'THREAT-INTEL', or 'LOCAL-CYBER'
    source TEXT NOT NULL,
    cve_id TEXT,            -- Populated for CISA Known Exploited Vulnerabilities
    severity TEXT NOT NULL, -- 'CRITICAL', 'HIGH', or 'ADVISORY'
    title TEXT NOT NULL,
    summary TEXT,
    link TEXT NOT NULL,
    content_hash TEXT UNIQUE NOT NULL,
    published_at TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. Geopolitical Conflict, Kinetic War & Macro-Economic Threat Matrix
CREATE TABLE IF NOT EXISTS conflict_and_macro_intel (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    domain TEXT NOT NULL,           -- 'WAR-KINETIC', 'MACRO-ECONOMIC', 'SUPPLY-CHAIN', 'GEOPOLITICAL'
    theater TEXT NOT NULL,          -- 'EAST-AFRICA', 'RED-SEA-MIDEAST', 'EASTERN-EUROPE', 'INDO-PACIFIC', 'GLOBAL'
    severity TEXT NOT NULL,         -- 'CRITICAL', 'ELEVATED', 'WATCH'
    headline TEXT NOT NULL,
    source TEXT NOT NULL,
    link TEXT NOT NULL,
    content_hash TEXT UNIQUE NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 5. Persistent Operator Memory (Stores tech stack, economic profile, priorities)
