-- 7. Contextual Calendar & Task Assistant Table
CREATE TABLE IF NOT EXISTS personal_tasks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    priority TEXT NOT NULL DEFAULT 'NORMAL', -- 'CRITICAL', 'HIGH', 'NORMAL'
    due_at TIMESTAMPTZ,
    notified BOOLEAN DEFAULT FALSE,
    completed BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 8. Information & Receipt Organizer (M-Pesa, Bank SMS, Invoices, Tickets)
CREATE TABLE IF NOT EXISTS personal_ledger (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ref_code TEXT,
    amount NUMERIC(12,2) NOT NULL DEFAULT 0,
    currency TEXT NOT NULL DEFAULT 'KES',
    counterparty TEXT NOT NULL,
    category TEXT NOT NULL,
    raw_summary TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 9. Quick Voice-to-Action Logger (Project Ideas, Lyrics, Code Architectures)
CREATE TABLE IF NOT EXISTS idea_vault (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tag TEXT NOT NULL,
    content TEXT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 10. Deep OSINT & Behavioral Intelligence Dossiers
CREATE TABLE IF NOT EXISTS osint_dossiers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    target_query TEXT NOT NULL,
    entity_type TEXT NOT NULL,         -- 'PERSON', 'ORGANIZATION', 'PLACE', 'TOPIC-IDEA'
    footprint_summary TEXT NOT NULL,   -- Cross-platform & public record synthesis
    social_and_public_links JSONB,     -- Discovered accounts, registries, archives, papers
    behavioral_profile TEXT NOT NULL,  -- Motives, cognitive biases, leverage, social dynamics
    strategic_approchement TEXT,       -- How the operator should interact, negotiate, or position
    created_at TIMESTAMPTZ DEFAULT NOW()
);

